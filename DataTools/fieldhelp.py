"""
v1.16.0 – field help (the help panel shown next to the field the user is in).

The catalogue i18n/field_help.json is generated by tools/fieldhelp/build_catalogue.py for every form field of the app
(knowledge base with meaning, format, example, rules and UAE notes in English and Arabic + a generic text per field type).
Company admins can change any text per language on Settings → Field help; those edits are kept in the company schema
(DataTools.FormSetting 'help:overrides') and are never overwritten by a new catalogue.

GET   /tools/api/field-help/?lang=ar            the catalogue for one language (+ the company's edits), ETag-cached
GET   /tools/api/field-help/?admin=1&q=&lang=   rows for the editor (key, label, type, screens, English, translation, edited)
PATCH /tools/api/field-help/                    {key, lang, w, f, x, r, u} – empty texts = back to the catalogue text
"""
import hashlib
import json
import os

from django.conf import settings
from rest_framework import status
from rest_framework.permissions import IsAuthenticated
from rest_framework.response import Response
from rest_framework.views import APIView

PARTS = ('w', 'f', 'x', 'r', 'u')
OVERRIDES = 'help:overrides'
_cache = {'mtime': None, 'data': None}


def catalogue_path():
    return os.path.join(getattr(settings, 'BASE_DIR', os.getcwd()), 'i18n', 'field_help.json')


def catalogue():
    """The generated catalogue (re-read when the file changes)."""
    p = catalogue_path()
    try:
        m = os.path.getmtime(p)
    except OSError:
        return {'version': '0', 'kb': {}, 'generic': {}, 'fields': {}, 'names': {}, 'ui': {}, 'stats': {}}
    if _cache['mtime'] != m:
        with open(p, encoding='utf-8') as fh:
            _cache['data'] = json.load(fh)
        _cache['mtime'] = m
    return _cache['data']


def overrides():
    from .models import FormSetting
    row = FormSetting.objects.filter(form=OVERRIDES).first()
    return (row.data if row else {}) or {}, row.updated_at.isoformat() if row else ''


def _lang_parts(parts_by_lang, lang):
    """The parts in the language (English when the language has no column – the frontend translates those through t())."""
    p = parts_by_lang.get(lang) if lang != 'en' else None
    return p or parts_by_lang.get('en') or {}


def for_language(lang):
    c = catalogue()
    ov, stamp = overrides()
    kb = {}
    for k, e in c.get('kb', {}).items():
        cc = {}
        for pack, v in (e.get('cc') or {}).items():
            cc[pack] = v.get(lang) if lang != 'en' and v.get(lang) else v.get('en', {})
        kb[k] = {'t': e['t'], 'ae': e['ae'], 'only': e.get('only') or [], 'txt': _lang_parts(e, lang), 'cc': cc,
                 'native': lang == 'en' or bool(e.get(lang)), 're': e.get('re', ''), 'nm': e.get('nm', '')}
    generic = {}
    for k, v in c.get('generic', {}).items():
        cc = {pack: (x.get(lang) if lang != 'en' and x.get(lang) else x.get('en', {})) for pack, x in (v.get('cc') or {}).items()}
        generic[k] = {'txt': _lang_parts(v, lang), 'native': lang == 'en' or bool(v.get(lang)), 'cc': cc}
    fields = {}
    for k, e in c.get('fields', {}).items():
        d = {'l': e['l'], 't': e['t'], 'kb': e.get('kb', '')}
        if lang == 'ar' and e.get('la'):
            d['la'] = e['la']
        if e.get('m'):
            d['m'] = e['m']
        if e.get('h'):
            d['h'] = e['h']
        fields[k] = d
    ui = {t: (tr if lang == 'ar' else t) for t, tr in (c.get('ui') or {}).items()}
    ovl = {k: v.get(lang) or {} for k, v in ov.items() if v.get(lang)}
    ver = hashlib.sha1(f"{c.get('version')}|{stamp}|{lang}".encode()).hexdigest()[:16]
    return {'version': ver, 'lang': lang, 'kb': kb, 'generic': generic, 'fields': fields, 'names': c.get('names', {}),
            'ui': ui, 'overrides': ovl}


def _can_edit(request):
    from AccessControl.access import ctx
    try:
        c = ctx(request)
        return c.admin or bool({'change_term', 'change_formsetting'} & c.codes)
    except Exception:
        return bool(getattr(request.user, 'is_superuser', False))


def _effective(c, ov, key, lang):
    """The texts a field shows in a language: company edit > knowledge base > generic of its type."""
    e = c['fields'].get(key) if key.startswith(('label:', 'name:')) else None
    base = {}
    if key.startswith('kb:'):
        base = _lang_parts(c['kb'].get(key[3:], {}), lang)
    elif key.startswith('generic:'):
        base = _lang_parts(c['generic'].get(key[8:], {}), lang)
    elif e is not None:
        if e.get('kb') and e['kb'] in c['kb']:
            base = _lang_parts(c['kb'][e['kb']], lang)
        else:
            g = _lang_parts(c['generic'].get(e['t']) or c['generic'].get('text', {}), lang)
            lab = (e.get('la') if lang == 'ar' else '') or e['l']
            base = {k: str(v).replace('{0}', lab) for k, v in g.items()}
    mine = (ov.get(key) or {}).get(lang) or {}
    return {p: mine.get(p) if mine.get(p) not in (None, '') else base.get(p, '') for p in PARTS}, bool(mine)


def known_key(c, key):
    if key.startswith('kb:'):
        return key[3:] in c.get('kb', {})
    if key.startswith('generic:'):
        return key[8:] in c.get('generic', {})
    return key in c.get('fields', {})


class FieldHelpView(APIView):
    permission_classes = [IsAuthenticated]

    def get(self, request):
        lang = (request.query_params.get('lang') or getattr(request, 'LANGUAGE_CODE', '') or 'en').split('-')[0][:8]
        if request.query_params.get('admin') == '1':
            return self._admin(request, lang)
        data = for_language(lang)
        etag = f'"fh-{data["version"]}"'
        if request.headers.get('If-None-Match') == etag:
            return Response(status=status.HTTP_304_NOT_MODIFIED)
        resp = Response(data)
        resp['ETag'] = etag
        resp['Cache-Control'] = 'private, max-age=0, must-revalidate'
        return resp

    def _admin(self, request, lang):
        if not _can_edit(request):
            return Response({'detail': 'Only company admins (or users with the right to change translations) can edit field help.'},
                            status=status.HTTP_403_FORBIDDEN)
        c = catalogue()
        ov, _ = overrides()
        q = (request.query_params.get('q') or '').strip().lower()
        only_edited = request.query_params.get('edited') == '1'
        only_generic = request.query_params.get('generic') == '1'
        keys = [f'kb:{k}' for k in c.get('kb', {})] + [f'generic:{k}' for k in c.get('generic', {})] + sorted(c.get('fields', {}))
        rows = []
        for k in keys:
            e = c['fields'].get(k, {})
            label = e.get('l') or k.split(':', 1)[1].replace('_', ' ')
            if q and q not in k.lower() and q not in label.lower() and not any(q in s.lower() for s in e.get('s', [])):
                continue
            if only_generic and (not k.startswith(('label:', 'name:')) or e.get('kb')):
                continue
            en, _ = _effective(c, ov, k, 'en')
            tr_, edited = _effective(c, ov, k, lang)
            if only_edited and not ((ov.get(k) or {}).get(lang) or (ov.get(k) or {}).get('en')):
                continue
            rows.append({'key': k, 'label': label, 'type': e.get('t', ''), 'kb': e.get('kb', k[3:] if k.startswith('kb:') else ''),
                         'screens': e.get('s', []), 'en': en, 'text': tr_, 'edited': edited or bool((ov.get(k) or {}).get('en'))})
        try:
            page = max(1, int(request.query_params.get('page') or 1))
        except ValueError:
            page = 1
        size = 50
        return Response({'count': len(rows), 'page': page, 'results': rows[(page - 1) * size: page * size], 'lang': lang,
                         'stats': c.get('stats', {}), 'can_edit': True})

    def patch(self, request):
        if not _can_edit(request):
            return Response({'detail': 'Only company admins (or users with the right to change translations) can edit field help.'},
                            status=status.HTTP_403_FORBIDDEN)
        d = request.data if hasattr(request.data, 'get') else {}
        key = str(d.get('key') or '').strip()
        lang = str(d.get('lang') or 'en').strip()[:8]
        c = catalogue()
        if not known_key(c, key):
            return Response({'key': [f'There is no field help called “{key}”. Pick a row from the list.']}, status=status.HTTP_400_BAD_REQUEST)
        unknown = [k for k in d.keys() if k not in PARTS + ('key', 'lang')]
        if unknown:
            return Response({k: ['Unknown part – use w (what it is), f (format), x (example), r (rules) or u (UAE note).'] for k in unknown},
                            status=status.HTTP_400_BAD_REQUEST)
        parts = {p: str(d.get(p) or '').strip()[:600] for p in PARTS if str(d.get(p) or '').strip()}
        from .models import FormSetting
        row, _ = FormSetting.objects.get_or_create(form=OVERRIDES)
        data = dict(row.data or {})
        cur = dict(data.get(key) or {})
        if parts:
            cur[lang] = parts
        else:
            cur.pop(lang, None)
        if cur:
            data[key] = cur
        else:
            data.pop(key, None)
        row.data = data
        if getattr(request.user, 'is_authenticated', False):
            row.updated_by = request.user
        row.save()
        text, edited = _effective(c, data, key, lang)
        return Response({'key': key, 'lang': lang, 'text': text, 'edited': edited})
