"""v1.50.0 – payslip with English and Arabic on the same page (labour-office request in the GCC).

Every label is printed in English on the left and in Arabic on the right; amounts are in the middle. Arabic names of
departments, designations, branches, salary components and employees come from the translations (Settings → Translations);
common salary component names have a built-in Arabic name; a name without Arabic is printed in English only.
"""
